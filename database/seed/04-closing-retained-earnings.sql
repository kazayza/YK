-- ============================================================
-- إعداد حساب الأرباح المرحلة لقيد الإقفال السنوي (حزمة الإقفال الحقيقي)
-- ============================================================
-- زر «توليد قيد الإقفال» في شاشة السنوات المالية يصفّر حسابات الإيرادات
-- (النوع 4) والتكلفة (النوع 5) والمصروفات (النوع 6) من قيود السنة المرحّلة
-- إلى حساب الأرباح المرحلة الذي يثبّته هذا الإعداد.
--
-- خطواتك:
--   1) شغّل هذا الملف مرة واحدة على قاعدة البيانات.
--   2) من شاشة الإعدادات (مجموعة «المحاسبة») املأ قيمة الإعداد بكود حساب
--      حقوق ملكية تفصيلي (النوع 3) من دليل حساباتك — حساب «الأرباح المرحلة»
--      أو «أرباح/خسائر مرحلة» — أو حدّث القيمة هنا مباشرة قبل التشغيل.
-- حتى تُملأ القيمة يرفض توليد قيد الإقفال برسالة صريحة، ويمنع إغلاق أي سنة
-- فيها نشاط نتيجة دون قيد إقفال.
-- ============================================================

IF NOT EXISTS (SELECT 1 FROM dbo.SystemSettings WHERE SettingKey = 'ClosingRetainedEarningsAccountCode')
BEGIN
    INSERT INTO dbo.SystemSettings (SettingKey, SettingValue, SettingDescription, SettingGroup, DataType)
    VALUES ('ClosingRetainedEarningsAccountCode', '', N'كود حساب الأرباح المرحلة الذي تُصفَّر إليه حسابات الإيرادات والتكلفة والمصروفات عند توليد قيد إقفال السنة المالية', 'Accounting', 'Text');
END
GO
